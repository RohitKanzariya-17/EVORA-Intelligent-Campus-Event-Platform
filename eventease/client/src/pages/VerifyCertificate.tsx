import React, { useEffect, useState } from 'react';
import { useParams, Link } from 'react-router-dom';
import {
  Award,
  CheckCircle2,
  XCircle,
  ShieldCheck,
  Calendar,
  Layers,
  ExternalLink,
  Printer,
  Share2,
  ArrowLeft,
} from 'lucide-react';
import toast from 'react-hot-toast';
import { certificateService } from '../services/api';
import { Certificate } from '../types';

export const VerifyCertificate: React.FC = () => {
  const { certificateId } = useParams<{ certificateId: string }>();

  const [certificate, setCertificate] = useState<Certificate | null>(null);
  const [isValid, setIsValid] = useState<boolean | null>(null);
  const [errorMessage, setErrorMessage] = useState('');
  const [isLoading, setIsLoading] = useState(true);

  useEffect(() => {
    if (!certificateId) {
      setIsLoading(false);
      setIsValid(false);
      setErrorMessage('No certificate ID provided in verification URL.');
      return;
    }

    const checkVerification = async () => {
      setIsLoading(true);
      try {
        const res = await certificateService.verifyCertificate(certificateId);
        if (res.valid && res.data) {
          setIsValid(true);
          setCertificate(res.data);
        } else {
          setIsValid(false);
          setErrorMessage(res.message || 'Certificate record could not be verified.');
          if (res.data) setCertificate(res.data);
        }
      } catch (err: any) {
        setIsValid(false);
        setErrorMessage(
          err.response?.data?.message || 'Certificate verification failed or record does not exist.'
        );
      } finally {
        setIsLoading(false);
      }
    };
    checkVerification();
  }, [certificateId]);

  const handlePrint = () => {
    window.print();
  };

  const handleShare = () => {
    if (navigator.share) {
      navigator.share({
        title: `Verified Certificate - ${certificate?.studentName}`,
        url: window.location.href,
      }).catch(() => {});
    } else {
      navigator.clipboard.writeText(window.location.href);
      toast.success('Verification URL copied to clipboard!');
    }
  };

  if (isLoading) {
    return (
      <div className="min-h-screen bg-[#F8FAFC] flex items-center justify-center p-4">
        <div className="bg-white p-8 rounded-xl border border-[#E2E8F0] shadow-xs max-w-md w-full text-center space-y-3">
          <div className="w-10 h-10 rounded-full border-3 border-[#2563EB] border-t-transparent animate-spin mx-auto" />
          <h2 className="text-base font-bold text-[#0F172A]">Verifying Digital Credential...</h2>
          <p className="text-xs text-[#64748B] font-mono break-all">{certificateId}</p>
        </div>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-[#F8FAFC] py-12 px-4 sm:px-6 lg:px-8">
      <div className="max-w-2xl mx-auto space-y-6">
        {/* Verification Status Banner */}
        {isValid ? (
          <div className="bg-[#F0FDF4] border border-[#DCFCE7] text-[#16A34A] p-4 rounded-xl shadow-xs flex items-center justify-between gap-4">
            <div className="flex items-center gap-3">
              <div className="w-9 h-9 rounded-lg bg-white border border-[#DCFCE7] flex items-center justify-center shrink-0">
                <CheckCircle2 className="w-5 h-5 text-[#22C55E]" />
              </div>
              <div>
                <h2 className="text-sm font-bold text-[#16A34A]">Authentic Certificate Verified</h2>
                <p className="text-xs text-[#15803D]">
                  This credential was generated by authorized campus organizers on EVORA.
                </p>
              </div>
            </div>

            <div className="hidden sm:flex items-center gap-2">
              <button
                onClick={handlePrint}
                className="p-2 bg-white hover:bg-[#F0FDF4] border border-[#DCFCE7] rounded-lg text-[#16A34A] transition"
                title="Print certificate"
              >
                <Printer className="w-4 h-4" />
              </button>
              <button
                onClick={handleShare}
                className="p-2 bg-white hover:bg-[#F0FDF4] border border-[#DCFCE7] rounded-lg text-[#16A34A] transition"
                title="Share verification link"
              >
                <Share2 className="w-4 h-4" />
              </button>
            </div>
          </div>
        ) : (
          <div className="bg-[#FEF2F2] border border-[#FEE2E2] text-[#DC2626] p-4 rounded-xl shadow-xs flex items-center gap-3">
            <div className="w-9 h-9 rounded-lg bg-white border border-[#FEE2E2] flex items-center justify-center shrink-0">
              <XCircle className="w-5 h-5 text-[#EF4444]" />
            </div>
            <div>
              <h2 className="text-sm font-bold text-[#DC2626]">Invalid or Revoked Credential</h2>
              <p className="text-xs text-[#B91C1C]">
                {errorMessage || 'This certificate identifier could not be validated against campus records.'}
              </p>
            </div>
          </div>
        )}

        {/* Certificate Card */}
        {certificate && (
          <div className="bg-white rounded-2xl border border-[#E2E8F0] p-8 sm:p-12 shadow-xs text-center relative overflow-hidden">
            {/* Top decorative badge */}
            <div className="w-14 h-14 rounded-2xl bg-[#EFF6FF] border border-[#DBEAFE] flex items-center justify-center text-[#2563EB] mx-auto mb-5 shadow-xs">
              <Award className="w-7 h-7" />
            </div>

            <div className="text-[11px] font-bold uppercase tracking-widest text-[#64748B] mb-2">
              Certificate of Event Participation
            </div>

            <h1 className="text-2xl sm:text-3xl font-bold text-[#0F172A] tracking-tight">
              {certificate.studentName}
            </h1>

            <p className="text-xs text-[#64748B] mt-2 max-w-md mx-auto leading-relaxed">
              has successfully participated in and satisfied the attendance criteria for
            </p>

            <div className="my-6 py-4 px-6 bg-[#F8FAFC] rounded-xl border border-[#E2E8F0] max-w-lg mx-auto">
              <div className="text-lg font-bold text-[#0F172A]">{certificate.eventTitle}</div>
              <div className="text-xs font-semibold text-[#2563EB] mt-0.5">
                {certificate.eventCategory}
              </div>
            </div>

            <p className="text-xs text-[#334155] max-w-md mx-auto">
              {certificate.eligibilityCriteria} • Attended {certificate.sessionsAttended} session(s)
            </p>

            {/* Credential Details Grid */}
            <div className="mt-8 pt-6 border-t border-[#E2E8F0] grid grid-cols-2 sm:grid-cols-3 gap-4 text-left text-xs">
              <div>
                <span className="block text-[10px] font-bold uppercase text-[#64748B]">
                  Issue Date
                </span>
                <span className="font-semibold text-[#0F172A]">
                  {new Date(certificate.issueDate).toLocaleDateString([], {
                    year: 'numeric',
                    month: 'long',
                    day: 'numeric',
                  })}
                </span>
              </div>

              <div>
                <span className="block text-[10px] font-bold uppercase text-[#64748B]">Status</span>
                <span
                  className={`inline-block font-bold px-2.5 py-0.5 rounded-full text-[10px] ${
                    certificate.status === 'Valid'
                      ? 'bg-[#F0FDF4] text-[#16A34A] border border-[#DCFCE7]'
                      : 'bg-[#FEF2F2] text-[#DC2626] border border-[#FEE2E2]'
                  }`}
                >
                  {certificate.status}
                </span>
              </div>

              <div className="col-span-2 sm:col-span-1">
                <span className="block text-[10px] font-bold uppercase text-[#64748B]">Issued By</span>
                <span className="font-semibold text-[#0F172A]">
                  {certificate.issuedBy?.name || 'Event Organizer'}
                </span>
              </div>
            </div>

            {/* Cryptographic ID Footer */}
            <div className="mt-8 pt-4 border-t border-[#E2E8F0] flex flex-col sm:flex-row items-center justify-between gap-3 text-xs text-[#64748B]">
              <div className="font-mono text-[10px] text-[#64748B]">
                Identifier: <span className="font-bold text-[#0F172A]">{certificate.certificateId}</span>
              </div>

              <div className="flex items-center gap-1.5 text-[11px] font-semibold text-[#2563EB]">
                <ShieldCheck className="w-4 h-4 text-[#2563EB]" />
                <span>Verified by EVORA Security</span>
              </div>
            </div>
          </div>
        )}

        {/* Back Link */}
        <div className="text-center">
          <Link
            to="/"
            className="text-xs font-semibold text-[#64748B] hover:text-[#0F172A] transition inline-flex items-center gap-1.5"
          >
            <ArrowLeft className="w-3.5 h-3.5" />
            <span>Return to EVORA Home</span>
          </Link>
        </div>
      </div>
    </div>
  );
};
